#!/usr/bin/env python3
"""Split the display face into self-hosted woff2 chunks with unicode-range.

The CSP is font-src 'self', so fonts cannot come from a CDN. Chunk 0 holds every
character the site uses today (pages, data, posts), so a normal page loads one
file. The rest of the face is split by code point; the browser only fetches a
chunk when a new character appears.

Source: Smiley Sans v2.0.1 (OFL-1.1, Reserved Font Names "Smiley" and "得意黑").
A subset is a Modified Version under the OFL, so the chunks are renamed
"Radar Display" and keep the original copyright and license notices.

  pip install fonttools brotli
  curl -LO https://github.com/atelier-anchor/smiley-sans/releases/download/v2.0.1/smiley-sans-v2.0.1.zip
  python3 scripts/build_fonts.py --source SmileySans-Oblique.ttf

Re-run after a large batch of new content; until then, new characters fall back
to the later chunks, never to tofu.
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / "public"
FONTS = PUBLIC / "assets" / "fonts"
FAMILY = "Radar Display"
PREFIX = "radar-display"
CHUNK = 450
CORPUS_GLOBS = (
    "public/**/*.html",
    "public/**/*.json",
    "public/assets/*.js",
    "public/*.txt",
    "content/posts/*.md",
)
# Always present even if the corpus does not have them yet.
BASELINE = (
    "".join(chr(cp) for cp in range(0x20, 0x7F))
    + "，。、；：？！“”‘’（）《》〈〉「」『』【】—…·～￥％＋－＝／"
    + "零一二三四五六七八九十百千万亿年月日时分秒周今昨明"
)


def corpus_codepoints() -> set[int]:
    seen: set[int] = set(map(ord, BASELINE))
    for pattern in CORPUS_GLOBS:
        for path in ROOT.glob(pattern):
            if FONTS in path.parents:
                continue
            try:
                text = path.read_text(encoding="utf-8")
            except (UnicodeDecodeError, OSError):
                continue
            seen.update(ord(ch) for ch in text)
    return seen


def ranges(codepoints: list[int]) -> str:
    """unicode-range value, merged into runs."""
    out = []
    start = prev = None
    for cp in sorted(codepoints):
        if start is None:
            start = prev = cp
            continue
        if cp == prev + 1:
            prev = cp
            continue
        out.append((start, prev))
        start = prev = cp
    if start is not None:
        out.append((start, prev))
    return ", ".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in out)


def rename(font) -> None:
    table = font["name"]
    for record in list(table.names):
        if record.nameID in (1, 3, 4, 6, 16, 17, 21, 22):
            table.removeNames(nameID=record.nameID)
    table.setName(FAMILY, 1, 3, 1, 0x409)
    table.setName("Regular", 2, 3, 1, 0x409)
    table.setName(f"{FAMILY}; derived from Smiley Sans v2.0.1", 3, 3, 1, 0x409)
    table.setName(FAMILY, 4, 3, 1, 0x409)
    table.setName(FAMILY.replace(" ", ""), 6, 3, 1, 0x409)


def build(source: Path) -> int:
    from fontTools import subset
    from fontTools.ttLib import TTFont

    base = TTFont(source)
    available = set(base.getBestCmap())
    used = corpus_codepoints() & available
    rest = sorted(available - used)
    chunks = [sorted(used)] + [rest[i : i + CHUNK] for i in range(0, len(rest), CHUNK)]

    FONTS.mkdir(parents=True, exist_ok=True)
    for old in FONTS.glob(f"{PREFIX}-*.woff2"):
        old.unlink()
    faces = []
    total = 0
    for index, cps in enumerate(chunks):
        font = TTFont(source)
        options = subset.Options()
        options.flavor = "woff2"
        options.layout_features = ["*"]
        options.name_IDs = ["*"]
        options.notdef_outline = False
        sub = subset.Subsetter(options)
        sub.populate(unicodes=cps)
        sub.subset(font)
        rename(font)
        tmp = FONTS / f"{PREFIX}-tmp.woff2"
        font.flavor = "woff2"
        font.save(tmp)
        digest = hashlib.sha256(tmp.read_bytes()).hexdigest()[:8]
        name = f"{PREFIX}-{index:02d}-{digest}.woff2"
        tmp.rename(FONTS / name)
        total += (FONTS / name).stat().st_size
        faces.append(
            "@font-face {\n"
            f'  font-family: "{FAMILY}";\n'
            f'  src: url("./{name}") format("woff2");\n'
            "  font-weight: 400 700;\n"
            "  font-style: normal;\n"
            "  font-display: swap;\n"
            f"  unicode-range: {ranges(cps)};\n"
            "}\n"
        )
    header = (
        "/* Generated by scripts/build_fonts.py. Do not edit by hand.\n"
        f" * {FAMILY}: subset of Smiley Sans v2.0.1 (c) atelierAnchor, SIL OFL 1.1. See LICENSE-OFL-smiley.txt.\n"
        " * Space Grotesk (c) The Space Grotesk Project Authors, SIL OFL 1.1. See LICENSE-OFL-space-grotesk.txt.\n"
        " */\n"
    )
    grotesk = "".join(
        "@font-face {\n"
        '  font-family: "Space Grotesk";\n'
        f'  src: url("./space-grotesk-latin-{weight}.woff2") format("woff2");\n'
        f"  font-weight: {weight};\n"
        "  font-style: normal;\n"
        "  font-display: swap;\n"
        "  unicode-range: U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, "
        "U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD;\n"
        "}\n"
        for weight in (400, 500, 700)
    )
    (FONTS / "fonts.css").write_text(header + "".join(faces) + grotesk, encoding="utf-8")
    first = FONTS / sorted(p.name for p in FONTS.glob(f"{PREFIX}-00-*.woff2"))[0]
    print(
        f"OK build_fonts: {len(chunks)} chunks, {total // 1024} KB total, "
        f"chunk 0 = {len(chunks[0])} chars / {first.stat().st_size // 1024} KB"
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--source", required=True, help="SmileySans-Oblique.ttf from the official release")
    args = parser.parse_args(argv)
    source = Path(args.source)
    if not source.is_file():
        print(f"FAIL: {source} not found", file=sys.stderr)
        return 1
    return build(source)


if __name__ == "__main__":
    sys.exit(main())
